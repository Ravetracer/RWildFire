/// `CrackleFunc.position`: centre of cell (x, y) for plane slice z, scale s, distortion d.
fn crackle_position(x: i32, y: i32, z: f64, s: f64, d: f64) -> (f64, f64) {
    let (xf, yf) = (x as f64, y as f64);
    if d == 0.0 {
        // d * noise == 0: identical result without evaluating the noise.
        return (xf * s, yf * s);
    }
    let e = [xf * 2.5, yf * 2.5, z * 2.5];
    let f = [yf * 2.5 + 30.2, xf * 2.5 - 12.1, z * 2.5 + 19.8];
    (
        (xf + d * simplex_noise3d(e)) * s,
        (yf + d * simplex_noise3d(f)) * s,
    )
}

const SQRT3: f64 = 1.732_050_807_568_877_2;
const HEX_A: f64 = 1.0 / 3.0;
const HEX_B: f64 = SQRT3 / 3.0;
const HEX_C: f64 = -1.0 / 3.0;
const HEX_D: f64 = SQRT3 / 3.0;
const CART_A: f64 = 1.5;
const CART_B: f64 = -1.5;
const CART_C: f64 = SQRT3 / 2.0;
const CART_D: f64 = SQRT3 / 2.0;

#[inline]
fn hex_cell_centre(x: i32, y: i32, s: f64) -> (f64, f64) {
    let (xf, yf) = (x as f64, y as f64);
    (
        (CART_A * xf + CART_B * yf) * s,
        (CART_C * xf + CART_D * yf) * s,
    )
}

/// hypertile1 / hypertile2 precalculation: [p, q, pa, r].
fn hypertile12_prepare(p: &[f64]) -> Vec<f64> {
    let pp = ftoi(p[0]).max(3.0);
    let qq = ftoi(p[1]).max(3.0);
    let pa = 2.0 * M_PI / pp;
    let r2 =
        1.0 - ((2.0 * M_PI / pp).cos() - 1.0) / ((2.0 * M_PI / pp).cos() + (2.0 * M_PI / qq).cos());
    let r = if r2 > 0.0 { 1.0 / r2.sqrt() } else { 1.0 };
    vec![pp, qq, pa, r]
}

