    const POINTS: &[(f64, f64, f64)] = &[
        (0.3, 0.2, 0.1),
        (-0.7, 0.5, -0.2),
        (1.3, -0.9, 0.4),
        (0.05, -0.02, 0.0),
        (-2.1, -1.7, 1.1),
        (0.6, 0.0, -0.5),
    ];

    fn run(def: &VarDef, data: &[f64], ctx: &mut Ctx, p: (f64, f64, f64)) -> (Pt, Pt) {
        let mut a = Pt {
            x: p.0,
            y: p.1,
            z: p.2,
            color: 0.5,
            ..Default::default()
        };
        let mut v = Pt {
            x: 0.1,
            y: -0.2,
            z: 0.05,
            color: 0.5,
            ..Default::default()
        };
        (def.apply)(data, ctx, &mut a, &mut v, 0.8);
        (a, v)
    }

    #[test]
    fn all_names_present_and_unique() {
        assert_eq!(DEFS.len(), NAMES.len());
        for n in NAMES {
            assert_eq!(DEFS.iter().filter(|d| d.name == *n).count(), 1, "{n}");
        }
    }

    #[test]
    fn default_params_give_finite_results() {
        let mut ctx = Ctx::new(42, true);
        for def in DEFS {
            let data = def.prepare_data(&[], &Affine::IDENTITY);
            assert!(def.supports_gpu(), "{} has no WGSL", def.name);
            for &p in POINTS {
                for _ in 0..50 {
                    let (a, v) = run(def, &data, &mut ctx, p);
                    assert!(
                        !a.is_bad() && !v.is_bad() && v.color.is_finite(),
                        "{} at {:?}: a={:?} v={:?}",
                        def.name,
                        p,
                        a,
                        v
                    );
                }
            }
        }
    }

    #[test]
    fn crackle_with_distortion_is_finite_and_bounded() {
        let def = DEFS.iter().find(|d| d.name == "crackle").unwrap();
        // small cells: many lookups outside the 21x21 cache window
        let data = def.prepare_data(&[0.05, 0.2, 0.6, 1.0, 0.3], &Affine::IDENTITY);
        let mut ctx = Ctx::new(7, false);
        for &p in POINTS {
            for _ in 0..200 {
                let (_, v) = run(def, &data, &mut ctx, p);
                assert!(!v.is_bad());
                assert!(v.x.abs() < 10.0 && v.y.abs() < 10.0);
            }
        }
    }

    #[test]
    fn simplex_noise_is_in_range() {
        let mut ctx = Ctx::new(3, false);
        let mut max: f64 = 0.0;
        for _ in 0..10000 {
            let p = [
                ctx.random() * 40.0 - 20.0,
                ctx.random() * 40.0 - 20.0,
                ctx.random() * 40.0 - 20.0,
            ];
            let n = simplex_noise3d(p);
            assert!(n.is_finite() && n.abs() <= 1.5, "{n}");
            max = max.max(n.abs());
        }
        assert!(max > 0.3);
    }

    #[test]
    fn hexes_identity_like() {
        // power 1, scale 1, no rotation: hexes maps a point onto itself
        let def = DEFS.iter().find(|d| d.name == "hexes").unwrap();
        let data = def.prepare_data(&[1.0, 1.0, 0.0, 1.0], &Affine::IDENTITY);
        let mut ctx = Ctx::new(1, false);
        let mut a = Pt {
            x: 0.37,
            y: -0.21,
            ..Default::default()
        };
        let mut v = Pt::default();
        (def.apply)(&data, &mut ctx, &mut a, &mut v, 1.0);
        assert!(
            (v.x - 0.37).abs() < 1e-9 && (v.y + 0.21).abs() < 1e-9,
            "{v:?}"
        );
    }
