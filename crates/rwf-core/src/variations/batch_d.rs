// ---------------------------------------------------------------------------------------------
// Voronoi helpers (`VoronoiTools`)
// ---------------------------------------------------------------------------------------------

fn vratio(p: (f64, f64), q: (f64, f64), u: (f64, f64)) -> f64 {
    let pmqx = p.0 - q.0;
    let pmqy = p.1 - q.1;
    if pmqx == 0.0 && pmqy == 0.0 {
        return 1.0;
    }
    2.0 * ((u.0 - q.0) * pmqx + (u.1 - q.1) * pmqy) / (pmqx * pmqx + pmqy * pmqy)
}

fn closest(p: &[(f64, f64)], u: (f64, f64)) -> usize {
    let mut d2min = 1.0e100;
    let mut j = 0;
    for (i, pt) in p.iter().enumerate() {
        let d2 = (pt.0 - u.0) * (pt.0 - u.0) + (pt.1 - u.1) * (pt.1 - u.1);
        if d2 < d2min {
            d2min = d2;
            j = i;
        }
    }
    j
}

fn voronoi(p: &[(f64, f64)], q: usize, u: (f64, f64)) -> f64 {
    let mut ratiomax = -1.0e100;
    for (i, pt) in p.iter().enumerate() {
        if i != q {
            let ratio = vratio(*pt, p[q], u);
            if ratio > ratiomax {
                ratiomax = ratio;
            }
        }
    }
    ratiomax
}

