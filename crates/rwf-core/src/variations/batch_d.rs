const SKEW_F3: f64 = 1.0 / 3.0;
const SKEW_G3: f64 = 1.0 / 6.0;

#[inline]
fn perm(i: i32) -> i32 {
    NOISE_PERM[(i & 0x3ff) as usize] as i32
}

fn simplex_noise3d(v: [f64; 3]) -> f64 {
    let skew_in = (v[0] + v[1] + v[2]) * SKEW_F3;
    let i = (v[0] + skew_in).floor() as i32;
    let j = (v[1] + skew_in).floor() as i32;
    let k = (v[2] + skew_in).floor() as i32;
    let t = (i + j + k) as f64 * SKEW_G3;
    let x0 = i as f64 - t;
    let y0 = j as f64 - t;
    let z0 = k as f64 - t;
    let mut c = [[0.0f64; 3]; 4];
    c[0] = [v[0] - x0, v[1] - y0, v[2] - z0];
    let (i1, j1, k1, i2, j2, k2);
    if c[0][0] >= c[0][1] {
        if c[0][1] >= c[0][2] {
            (i1, j1, k1, i2, j2, k2) = (1, 0, 0, 1, 1, 0);
        } else if c[0][0] >= c[0][2] {
            (i1, j1, k1, i2, j2, k2) = (1, 0, 0, 1, 0, 1);
        } else {
            (i1, j1, k1, i2, j2, k2) = (0, 0, 1, 1, 0, 1);
        }
    } else if c[0][1] < c[0][2] {
        (i1, j1, k1, i2, j2, k2) = (0, 0, 1, 0, 1, 1);
    } else if c[0][0] < c[0][2] {
        (i1, j1, k1, i2, j2, k2) = (0, 1, 0, 0, 1, 1);
    } else {
        (i1, j1, k1, i2, j2, k2) = (0, 1, 0, 1, 1, 0);
    }
    c[1] = [
        c[0][0] - i1 as f64 + SKEW_G3,
        c[0][1] - j1 as f64 + SKEW_G3,
        c[0][2] - k1 as f64 + SKEW_G3,
    ];
    c[2] = [
        c[0][0] - i2 as f64 + 2.0 * SKEW_G3,
        c[0][1] - j2 as f64 + 2.0 * SKEW_G3,
        c[0][2] - k2 as f64 + 2.0 * SKEW_G3,
    ];
    c[3] = [
        c[0][0] - 1.0 + 3.0 * SKEW_G3,
        c[0][1] - 1.0 + 3.0 * SKEW_G3,
        c[0][2] - 1.0 + 3.0 * SKEW_G3,
    ];
    let ii = i & 0x3ff;
    let jj = j & 0x3ff;
    let kk = k & 0x3ff;
    // The Java table repeats every 1024 entries, so indexing modulo 1024 is identical.
    let gi = [
        perm(ii + perm(jj + perm(kk))),
        perm(ii + i1 + perm(jj + j1 + perm(kk + k1))),
        perm(ii + i2 + perm(jj + j2 + perm(kk + k2))),
        perm(ii + 1 + perm(jj + 1 + perm(kk + 1))),
    ];
    let mut n = 0.0;
    for corner in 0..4 {
        let cc = c[corner];
        let mut t = 0.6 - cc[0] * cc[0] - cc[1] * cc[1] - cc[2] * cc[2];
        if t > 0.0 {
            let g = NOISE_GRAD3[gi[corner] as usize];
            t *= t;
            n += t * t * (g[0] * cc[0] + g[1] * cc[1] + g[2] * cc[2]);
        }
    }
    32.0 * n
}

