"""Extracts the built-in tilings of Taprats (JWildfire `csk/taprats/tile/Tiling.java`, static
block) into `assets/taprats/tilings.txt`, read by the `taprats` variation.

Format, one item per line:

    tiling <name>
    trans <t1x> <t1y> <t2x> <t2y>
    regular <n>                      (a regular n-gon feature)
    polygon <x0> <y0> <x1> <y1> ...  (an explicit feature)
    place <a> <b> <c> <d> <e> <f>    (a placement of the last feature)

The tilings are Taprats data (GPL-3.0-or-later), used by the optional `taprats` feature.

Numbers keep the spelling of the Java source (the `D` suffix removed), so they parse to the
same doubles.

    python3 tools/gen_taprats_tilings.py <JWildfire>/src/csk/taprats/tile/Tiling.java
"""

import re
import sys
from pathlib import Path

NUM = r"[-+]?(?:\d+\.?\d*|\.\d+)(?:[eE][-+]?\d+)?[dDfF]?"


def num(s):
    return s.rstrip("dDfF")


def main():
    src = Path(sys.argv[1]).read_text(encoding="utf-8")
    body = src[src.index("builtins = new Hashtable();"):]
    body = re.sub(r"/\*.*?\*/", "", body, flags=re.S)
    body = re.sub(r"//[^\n]*", "", body)
    body = re.sub(r'"(?:[^"\\]|\\.)*"', '""', body)
    call = re.compile(r"\b(beginTiling|setTranslations|beginPolygonFeature|addPoint|commitPolygonFeature|addPlacement|endFeature|beginRegularFeature|endTiling)\s*\(")
    out = []
    names = re.findall(r'beginTiling\s*\(\s*"([^"]*)"', re.sub(r"//[^\n]*", "", re.sub(r"/\*.*?\*/", "", src[src.index("builtins = new Hashtable();"):], flags=re.S)))
    name_iter = iter(names)
    poly = None
    pos = 0
    while (m := call.search(body, pos)) is not None:
        # arguments up to the matching parenthesis
        depth, i = 1, m.end()
        while depth:
            depth += {"(": 1, ")": -1}.get(body[i], 0)
            i += 1
        args = re.findall(NUM, body[m.end():i - 1])
        pos = i
        f = m.group(1)
        if f == "beginTiling":
            out.append(f"tiling {next(name_iter)}")
        elif f == "setTranslations":
            out.append("trans " + " ".join(num(a) for a in args))
        elif f == "beginPolygonFeature":
            poly = []
        elif f == "addPoint":
            poly.extend(num(a) for a in args)
        elif f == "commitPolygonFeature":
            out.append("polygon " + " ".join(poly))
        elif f == "beginRegularFeature":
            out.append(f"regular {num(args[0])}")
        elif f == "addPlacement":
            assert len(args) == 6, args
            out.append("place " + " ".join(num(a) for a in args))
    dest = Path(__file__).resolve().parent.parent / "assets" / "taprats" / "tilings.txt"
    dest.parent.mkdir(parents=True, exist_ok=True)
    dest.write_text("# Built-in tilings of Taprats (Craig S. Kaplan), from JWildfire's Tiling.java.\n# GPL-3.0-or-later; only used by the optional `taprats` feature.\n# Generated by tools/gen_taprats_tilings.py\n" + "\n".join(out) + "\n", encoding="utf-8")
    print(f"{len(names)} tilings -> {dest}")


if __name__ == "__main__":
    main()
